/**
 * A species id that is deliberately NOT in the corpus.
 *
 * The engine is tested against injected fixtures — `simulate(config, corpus)` is called with a
 * hand-built corpus of invented creatures ("grower", "flat", "attacker") precisely so a mechanic can
 * be pinned without a real creature's other abilities interfering. Those ids are not `Species`
 * members and must not be: adding test data to the production vocabulary would make `Species` a
 * list of 149 species plus whatever a test needed last week.
 *
 * So this is the one sanctioned way to produce a non-corpus id, and it is a function rather than a
 * bare `as Species` cast at each site so that the intent is searchable and the exception is counted.
 * `provenance.test.ts` asserts no REAL corpus record uses it.
 */
export function syntheticSpecies(name: string): Species {
  return name as Species;
}

/** The `syntheticSpecies` equivalent for trinkets, used by engine fixtures. */
export function syntheticTrinketId(name: string): TrinketId {
  return name as TrinketId;
}
